CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE cargos (
    id_cargo              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(60) NOT NULL UNIQUE,
    descripcion           VARCHAR(200) NULL,
    activo                BOOLEAN NOT NULL CONSTRAINT df_cargo_activo DEFAULT TRUE
);

CREATE TABLE especialidades (
    id_especialidad       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(60) NOT NULL UNIQUE,
    descripcion           VARCHAR(200) NULL,
    activo                BOOLEAN NOT NULL CONSTRAINT df_especialidad_activo DEFAULT TRUE
);

CREATE TABLE roles (
    id_rol                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(50) NOT NULL UNIQUE,
    descripcion           VARCHAR(200) NULL,
    activo                BOOLEAN NOT NULL CONSTRAINT df_rol_activo DEFAULT TRUE
);

CREATE TABLE permisos (
    id_permiso            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(60) NOT NULL UNIQUE,
    nombre                VARCHAR(80) NOT NULL,
    descripcion           VARCHAR(200) NULL,
    activo                BOOLEAN NOT NULL CONSTRAINT df_permiso_activo DEFAULT TRUE
);

CREATE TABLE trabajadores (
    id_trabajador         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cargo              INT NOT NULL,
    cedula                VARCHAR(20) NOT NULL UNIQUE,
    primer_nombre         VARCHAR(50) NOT NULL,
    segundo_nombre        VARCHAR(50) NULL,
    primer_apellido       VARCHAR(50) NOT NULL,
    segundo_apellido      VARCHAR(50) NULL,
    telefono              VARCHAR(20) NULL,
    correo                VARCHAR(100) NULL,
    direccion             VARCHAR(200) NULL,
    fecha_ingreso         DATE NOT NULL,
    estado                VARCHAR(15) NOT NULL,
    CONSTRAINT fk_trabajador_cargo FOREIGN KEY (id_cargo) REFERENCES cargos(id_cargo),
    CONSTRAINT ck_trabajador_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE UNIQUE INDEX ux_trabajador_correo
    ON trabajadores(correo) WHERE correo IS NOT NULL;

CREATE TABLE usuarios (
    id_usuario            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_trabajador         INT NULL,
    nombre_usuario        VARCHAR(60) NOT NULL UNIQUE,
    password_hash         VARCHAR(255) NOT NULL,
    estado                VARCHAR(15) NOT NULL,
    creado_en             TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_usuario_creado DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso         TIMESTAMPTZ(0) NULL,
    CONSTRAINT fk_usuario_trabajador FOREIGN KEY (id_trabajador) REFERENCES trabajadores(id_trabajador),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO','BLOQUEADO','INACTIVO'))
);

CREATE UNIQUE INDEX ux_usuario_trabajador
    ON usuarios(id_trabajador) WHERE id_trabajador IS NOT NULL;

CREATE TABLE usuarios_rol (
    id_usuario_rol        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            INT NOT NULL,
    id_rol                INT NOT NULL,
    fecha_inicio          DATE NOT NULL,
    fecha_fin             DATE NULL,
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (id_rol) REFERENCES roles(id_rol),
    CONSTRAINT uq_usuario_rol_periodo UNIQUE (id_usuario, id_rol, fecha_inicio),
    CONSTRAINT ck_usuario_rol_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE UNIQUE INDEX ux_usuario_rol_activo
    ON usuarios_rol(id_usuario, id_rol) WHERE fecha_fin IS NULL;

CREATE TABLE roles_permiso (
    id_rol                INT NOT NULL,
    id_permiso            INT NOT NULL,
    CONSTRAINT pk_rol_permiso PRIMARY KEY (id_rol, id_permiso),
    CONSTRAINT fk_rol_permiso_rol FOREIGN KEY (id_rol) REFERENCES roles(id_rol),
    CONSTRAINT fk_rol_permiso_permiso FOREIGN KEY (id_permiso) REFERENCES permisos(id_permiso)
);

CREATE TABLE auditorias (
    id_auditoria          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            INT NULL,
    entidad               VARCHAR(60) NOT NULL,
    id_registro           VARCHAR(50) NOT NULL,
    accion                VARCHAR(20) NOT NULL,
    campo                 VARCHAR(60) NULL,
    valor_anterior        VARCHAR(1000) NULL,
    valor_nuevo           VARCHAR(1000) NULL,
    fecha_hora            TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_auditoria_fecha DEFAULT CURRENT_TIMESTAMP,
    ip_origen             INET NULL,
    uuid_operacion        UUID NOT NULL CONSTRAINT df_auditoria_uuid DEFAULT gen_random_uuid(),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_auditoria_accion CHECK (accion IN ('CREAR','MODIFICAR','ANULAR','APROBAR','RECHAZAR'))
);

CREATE UNIQUE INDEX ux_auditoria_uuid ON auditorias(uuid_operacion);

CREATE TABLE obras (
    id_obra               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(20) NOT NULL UNIQUE,
    nombre                VARCHAR(120) NOT NULL,
    descripcion           VARCHAR(500) NULL,
    direccion             VARCHAR(200) NOT NULL,
    fecha_inicio_plan     DATE NOT NULL,
    fecha_fin_plan        DATE NOT NULL,
    fecha_inicio_real     DATE NULL,
    fecha_fin_real        DATE NULL,
    estado                VARCHAR(20) NOT NULL,
    creado_en             TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_obra_creado DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_obra_estado CHECK (estado IN ('PLANIFICADA','ACTIVA','SUSPENDIDA','FINALIZADA')),
    CONSTRAINT ck_obra_fechas_plan CHECK (fecha_fin_plan >= fecha_inicio_plan),
    CONSTRAINT ck_obra_fechas_real CHECK (fecha_fin_real IS NULL OR fecha_inicio_real IS NULL OR fecha_fin_real >= fecha_inicio_real)
);

CREATE TABLE cuadrillas (
    id_cuadrilla          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(20) NOT NULL UNIQUE,
    nombre                VARCHAR(80) NOT NULL,
    descripcion           VARCHAR(200) NULL,
    activo                BOOLEAN NOT NULL CONSTRAINT df_cuadrilla_activo DEFAULT TRUE
);

CREATE TABLE trabajadores_especialidad (
    id_trabajador         INT NOT NULL,
    id_especialidad       INT NOT NULL,
    nivel                 VARCHAR(20) NULL,
    fecha_certificacion   DATE NULL,
    fecha_vencimiento     DATE NULL,
    CONSTRAINT pk_trabajador_especialidad PRIMARY KEY (id_trabajador, id_especialidad),
    CONSTRAINT fk_te_trabajador FOREIGN KEY (id_trabajador) REFERENCES trabajadores(id_trabajador),
    CONSTRAINT fk_te_especialidad FOREIGN KEY (id_especialidad) REFERENCES especialidades(id_especialidad),
    CONSTRAINT ck_te_nivel CHECK (nivel IS NULL OR nivel IN ('BASICO','INTERMEDIO','AVANZADO','CERTIFICADO')),
    CONSTRAINT ck_te_fechas CHECK (fecha_vencimiento IS NULL OR fecha_certificacion IS NULL OR fecha_vencimiento >= fecha_certificacion)
);

CREATE TABLE asignaciones_trabajador_obra (
    id_asignacion         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_trabajador         INT NOT NULL,
    id_obra               INT NOT NULL,
    id_especialidad       INT NULL,
    tipo_contratacion     VARCHAR(20) NOT NULL,
    fecha_inicio          DATE NOT NULL,
    fecha_fin             DATE NULL,
    es_responsable        BOOLEAN NOT NULL CONSTRAINT df_ato_responsable DEFAULT FALSE,
    estado                VARCHAR(15) NOT NULL,
    CONSTRAINT fk_ato_trabajador FOREIGN KEY (id_trabajador) REFERENCES trabajadores(id_trabajador),
    CONSTRAINT fk_ato_obra FOREIGN KEY (id_obra) REFERENCES obras(id_obra),
    CONSTRAINT fk_ato_especialidad FOREIGN KEY (id_trabajador, id_especialidad)
        REFERENCES trabajadores_especialidad(id_trabajador, id_especialidad),
    CONSTRAINT uq_ato_periodo UNIQUE (id_trabajador, id_obra, fecha_inicio),
    CONSTRAINT ck_ato_tipo CHECK (tipo_contratacion IN ('FIJO','SUBCONTRATADO','TEMPORAL')),
    CONSTRAINT ck_ato_estado CHECK (estado IN ('ACTIVA','FINALIZADA','ANULADA')),
    CONSTRAINT ck_ato_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE UNIQUE INDEX ux_ato_activa
    ON asignaciones_trabajador_obra(id_trabajador, id_obra) WHERE fecha_fin IS NULL AND estado = 'ACTIVA';

CREATE TABLE cuadrillas_obra (
    id_cuadrilla_obra     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuadrilla          INT NOT NULL,
    id_obra               INT NOT NULL,
    fecha_inicio          DATE NOT NULL,
    fecha_fin             DATE NULL,
    estado                VARCHAR(15) NOT NULL,
    CONSTRAINT fk_co_cuadrilla FOREIGN KEY (id_cuadrilla) REFERENCES cuadrillas(id_cuadrilla),
    CONSTRAINT fk_co_obra FOREIGN KEY (id_obra) REFERENCES obras(id_obra),
    CONSTRAINT uq_co_periodo UNIQUE (id_cuadrilla, id_obra, fecha_inicio),
    CONSTRAINT ck_co_estado CHECK (estado IN ('ACTIVA','FINALIZADA','ANULADA')),
    CONSTRAINT ck_co_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE UNIQUE INDEX ux_cuadrilla_obra_activa
    ON cuadrillas_obra(id_cuadrilla, id_obra) WHERE fecha_fin IS NULL AND estado = 'ACTIVA';

CREATE TABLE trabajadores_cuadrilla (
    id_trabajador_cuadrilla INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asignacion         INT NOT NULL,
    id_cuadrilla_obra     INT NOT NULL,
    fecha_inicio          DATE NOT NULL,
    fecha_fin             DATE NULL,
    CONSTRAINT fk_tc_asignacion FOREIGN KEY (id_asignacion) REFERENCES asignaciones_trabajador_obra(id_asignacion),
    CONSTRAINT fk_tc_cuadrilla_obra FOREIGN KEY (id_cuadrilla_obra) REFERENCES cuadrillas_obra(id_cuadrilla_obra),
    CONSTRAINT uq_tc_periodo UNIQUE (id_asignacion, id_cuadrilla_obra, fecha_inicio),
    CONSTRAINT ck_tc_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE UNIQUE INDEX ux_trabajador_cuadrilla_activa
    ON trabajadores_cuadrilla(id_asignacion) WHERE fecha_fin IS NULL;

CREATE TABLE asistencias (
    id_asistencia         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asignacion         INT NOT NULL,
    fecha_jornada         DATE NOT NULL,
    entrada_at            TIMESTAMPTZ(0) NOT NULL,
    salida_at             TIMESTAMPTZ(0) NULL,
    latitud_entrada       NUMERIC(9,6) NULL,
    longitud_entrada      NUMERIC(9,6) NULL,
    latitud_salida        NUMERIC(9,6) NULL,
    longitud_salida       NUMERIC(9,6) NULL,
    estado                VARCHAR(15) NOT NULL,
    id_usuario_registro   INT NOT NULL,
    uuid_registro         UUID NOT NULL CONSTRAINT df_asistencia_uuid DEFAULT gen_random_uuid(),
    creado_en             TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_asistencia_creado DEFAULT CURRENT_TIMESTAMP,
    sincronizado_en       TIMESTAMPTZ(0) NULL,
    CONSTRAINT fk_asistencia_asignacion FOREIGN KEY (id_asignacion) REFERENCES asignaciones_trabajador_obra(id_asignacion),
    CONSTRAINT fk_asistencia_usuario FOREIGN KEY (id_usuario_registro) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_asistencia_estado CHECK (estado IN ('ABIERTA','COMPLETA','CORREGIDA','ANULADA')),
    CONSTRAINT ck_asistencia_horas CHECK (salida_at IS NULL OR salida_at >= entrada_at),
    CONSTRAINT ck_asistencia_lat_entrada CHECK (latitud_entrada IS NULL OR latitud_entrada BETWEEN -90 AND 90),
    CONSTRAINT ck_asistencia_lon_entrada CHECK (longitud_entrada IS NULL OR longitud_entrada BETWEEN -180 AND 180),
    CONSTRAINT ck_asistencia_lat_salida CHECK (latitud_salida IS NULL OR latitud_salida BETWEEN -90 AND 90),
    CONSTRAINT ck_asistencia_lon_salida CHECK (longitud_salida IS NULL OR longitud_salida BETWEEN -180 AND 180)
);

CREATE UNIQUE INDEX ux_asistencia_uuid ON asistencias(uuid_registro);
CREATE UNIQUE INDEX ux_asistencia_marcacion ON asistencias(id_asignacion, entrada_at);

CREATE TABLE correcciones_asistencia (
    id_correccion         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asistencia         BIGINT NOT NULL,
    id_usuario_solicita   INT NOT NULL,
    id_usuario_aprueba    INT NULL,
    entrada_anterior      TIMESTAMPTZ(0) NULL,
    salida_anterior       TIMESTAMPTZ(0) NULL,
    entrada_nueva         TIMESTAMPTZ(0) NULL,
    salida_nueva          TIMESTAMPTZ(0) NULL,
    motivo                VARCHAR(300) NOT NULL,
    estado                VARCHAR(15) NOT NULL,
    solicitado_en         TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_ca_solicitado DEFAULT CURRENT_TIMESTAMP,
    resuelto_en           TIMESTAMPTZ(0) NULL,
    CONSTRAINT fk_ca_asistencia FOREIGN KEY (id_asistencia) REFERENCES asistencias(id_asistencia),
    CONSTRAINT fk_ca_solicita FOREIGN KEY (id_usuario_solicita) REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_ca_aprueba FOREIGN KEY (id_usuario_aprueba) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_ca_estado CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA','ANULADA')),
    CONSTRAINT ck_ca_horas CHECK (salida_nueva IS NULL OR entrada_nueva IS NULL OR salida_nueva >= entrada_nueva)
);

CREATE TABLE actividades (
    id_actividad          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_obra               INT NOT NULL,
    id_asignacion_responsable INT NULL,
    codigo                VARCHAR(30) NOT NULL,
    nombre                VARCHAR(120) NOT NULL,
    descripcion           VARCHAR(500) NULL,
    unidad_medida         VARCHAR(20) NOT NULL,
    cantidad_planificada  NUMERIC(12,2) NOT NULL,
    fecha_inicio_plan     DATE NOT NULL,
    fecha_fin_plan        DATE NOT NULL,
    estado                VARCHAR(20) NOT NULL,
    CONSTRAINT fk_actividad_obra FOREIGN KEY (id_obra) REFERENCES obras(id_obra),
    CONSTRAINT fk_actividad_responsable FOREIGN KEY (id_asignacion_responsable) REFERENCES asignaciones_trabajador_obra(id_asignacion),
    CONSTRAINT uq_actividad_codigo UNIQUE (id_obra, codigo),
    CONSTRAINT ck_actividad_cantidad CHECK (cantidad_planificada >= 0),
    CONSTRAINT ck_actividad_fechas CHECK (fecha_fin_plan >= fecha_inicio_plan),
    CONSTRAINT ck_actividad_estado CHECK (estado IN ('PLANIFICADA','EN_PROCESO','COMPLETA','RETRASADA','CANCELADA'))
);

CREATE TABLE trabajadores_actividad (
    id_actividad          INT NOT NULL,
    id_asignacion         INT NOT NULL,
    rol_participacion     VARCHAR(50) NULL,
    CONSTRAINT pk_trabajador_actividad PRIMARY KEY (id_actividad, id_asignacion),
    CONSTRAINT fk_ta_actividad FOREIGN KEY (id_actividad) REFERENCES actividades(id_actividad),
    CONSTRAINT fk_ta_asignacion FOREIGN KEY (id_asignacion) REFERENCES asignaciones_trabajador_obra(id_asignacion)
);

CREATE TABLE avances (
    id_avance             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_actividad          INT NOT NULL,
    fecha_avance          DATE NOT NULL,
    cantidad_ejecutada    NUMERIC(12,2) NOT NULL,
    observaciones         VARCHAR(500) NULL,
    estado                VARCHAR(20) NOT NULL,
    id_usuario_registro   INT NOT NULL,
    uuid_registro         UUID NOT NULL CONSTRAINT df_avance_uuid DEFAULT gen_random_uuid(),
    creado_en             TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_avance_creado DEFAULT CURRENT_TIMESTAMP,
    sincronizado_en       TIMESTAMPTZ(0) NULL,
    CONSTRAINT fk_avance_actividad FOREIGN KEY (id_actividad) REFERENCES actividades(id_actividad),
    CONSTRAINT fk_avance_usuario FOREIGN KEY (id_usuario_registro) REFERENCES usuarios(id_usuario),
    CONSTRAINT uq_avance_dia UNIQUE (id_actividad, fecha_avance),
    CONSTRAINT ck_avance_cantidad CHECK (cantidad_ejecutada >= 0),
    CONSTRAINT ck_avance_estado CHECK (estado IN ('BORRADOR','REGISTRADO','ANULADO'))
);

CREATE UNIQUE INDEX ux_avance_uuid ON avances(uuid_registro);

CREATE TABLE evidencias (
    id_evidencia          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_avance             BIGINT NOT NULL,
    tipo_evidencia        VARCHAR(20) NOT NULL,
    ruta_archivo          VARCHAR(500) NOT NULL,
    hash_archivo          CHAR(64) NOT NULL,
    capturada_en          TIMESTAMPTZ(0) NOT NULL,
    latitud               NUMERIC(9,6) NULL,
    longitud              NUMERIC(9,6) NULL,
    id_usuario_registro   INT NOT NULL,
    uuid_registro         UUID NOT NULL CONSTRAINT df_evidencia_uuid DEFAULT gen_random_uuid(),
    creado_en             TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_evidencia_creado DEFAULT CURRENT_TIMESTAMP,
    sincronizado_en       TIMESTAMPTZ(0) NULL,
    CONSTRAINT fk_evidencia_avance FOREIGN KEY (id_avance) REFERENCES avances(id_avance),
    CONSTRAINT fk_evidencia_usuario FOREIGN KEY (id_usuario_registro) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_evidencia_tipo CHECK (tipo_evidencia IN ('FOTOGRAFIA','BITACORA','DOCUMENTO')),
    CONSTRAINT ck_evidencia_lat CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_evidencia_lon CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180)
);

CREATE UNIQUE INDEX ux_evidencia_uuid ON evidencias(uuid_registro);

CREATE TABLE incidencias (
    id_incidencia         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_obra               INT NOT NULL,
    tipo_incidencia       VARCHAR(30) NOT NULL,
    inicio_en             TIMESTAMPTZ(0) NOT NULL,
    fin_en                TIMESTAMPTZ(0) NULL,
    horas_perdidas        NUMERIC(8,2) NULL,
    descripcion           VARCHAR(500) NOT NULL,
    justificacion         VARCHAR(500) NULL,
    estado                VARCHAR(20) NOT NULL,
    id_usuario_registro   INT NOT NULL,
    uuid_registro         UUID NOT NULL CONSTRAINT df_incidencia_uuid DEFAULT gen_random_uuid(),
    creado_en             TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_incidencia_creado DEFAULT CURRENT_TIMESTAMP,
    sincronizado_en       TIMESTAMPTZ(0) NULL,
    CONSTRAINT fk_incidencia_obra FOREIGN KEY (id_obra) REFERENCES obras(id_obra),
    CONSTRAINT fk_incidencia_usuario FOREIGN KEY (id_usuario_registro) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_incidencia_tipo CHECK (tipo_incidencia IN ('CLIMA','MATERIAL_IMPORTADO','TECNICA','SEGURIDAD','OTRA')),
    CONSTRAINT ck_incidencia_estado CHECK (estado IN ('ABIERTA','RESUELTA','ANULADA')),
    CONSTRAINT ck_incidencia_fechas CHECK (fin_en IS NULL OR fin_en >= inicio_en),
    CONSTRAINT ck_incidencia_horas CHECK (horas_perdidas IS NULL OR horas_perdidas >= 0)
);

CREATE UNIQUE INDEX ux_incidencia_uuid ON incidencias(uuid_registro);

CREATE TABLE actividades_incidencia (
    id_incidencia         BIGINT NOT NULL,
    id_actividad          INT NOT NULL,
    CONSTRAINT pk_actividad_incidencia PRIMARY KEY (id_incidencia, id_actividad),
    CONSTRAINT fk_ai_incidencia FOREIGN KEY (id_incidencia) REFERENCES incidencias(id_incidencia),
    CONSTRAINT fk_ai_actividad FOREIGN KEY (id_actividad) REFERENCES actividades(id_actividad)
);

CREATE TABLE actas (
    id_acta               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_obra               INT NOT NULL,
    numero_acta           VARCHAR(30) NOT NULL,
    periodo_inicio        DATE NOT NULL,
    periodo_fin           DATE NOT NULL,
    observaciones         VARCHAR(1000) NULL,
    mejoras_propuestas    VARCHAR(500) NULL,
    solicitudes_cambio    VARCHAR(500) NULL,
    estado                VARCHAR(20) NOT NULL,
    id_usuario_creador    INT NOT NULL,
    uuid_registro         UUID NOT NULL CONSTRAINT df_acta_uuid DEFAULT gen_random_uuid(),
    creado_en             TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_acta_creado DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_acta_obra FOREIGN KEY (id_obra) REFERENCES obras(id_obra),
    CONSTRAINT fk_acta_usuario FOREIGN KEY (id_usuario_creador) REFERENCES usuarios(id_usuario),
    CONSTRAINT uq_acta_numero UNIQUE (id_obra, numero_acta),
    CONSTRAINT ck_acta_periodo CHECK (periodo_fin >= periodo_inicio),
    CONSTRAINT ck_acta_estado CHECK (estado IN ('BORRADOR','PENDIENTE','APROBADA','RECHAZADA','ANULADA'))
);

CREATE UNIQUE INDEX ux_acta_uuid ON actas(uuid_registro);

CREATE TABLE actas_avance (
    id_acta               INT NOT NULL,
    id_avance             BIGINT NOT NULL,
    CONSTRAINT pk_acta_avance PRIMARY KEY (id_acta, id_avance),
    CONSTRAINT fk_acta_avance_acta FOREIGN KEY (id_acta) REFERENCES actas(id_acta),
    CONSTRAINT fk_acta_avance_avance FOREIGN KEY (id_avance) REFERENCES avances(id_avance)
);

CREATE TABLE actas_incidencia (
    id_acta               INT NOT NULL,
    id_incidencia         BIGINT NOT NULL,
    CONSTRAINT pk_acta_incidencia PRIMARY KEY (id_acta, id_incidencia),
    CONSTRAINT fk_acta_incidencia_acta FOREIGN KEY (id_acta) REFERENCES actas(id_acta),
    CONSTRAINT fk_acta_incidencia_incidencia FOREIGN KEY (id_incidencia) REFERENCES incidencias(id_incidencia)
);

CREATE TABLE trabajadores_acta (
    id_acta               INT NOT NULL,
    id_asignacion         INT NOT NULL,
    tipo_participacion    VARCHAR(30) NOT NULL,
    ruta_firma            VARCHAR(500) NULL,
    firmado_en            TIMESTAMPTZ(0) NULL,
    CONSTRAINT pk_trabajador_acta PRIMARY KEY (id_acta, id_asignacion),
    CONSTRAINT fk_trabajador_acta_acta FOREIGN KEY (id_acta) REFERENCES actas(id_acta),
    CONSTRAINT fk_trabajador_acta_asignacion FOREIGN KEY (id_asignacion) REFERENCES asignaciones_trabajador_obra(id_asignacion)
);

CREATE TABLE aprobaciones_acta (
    id_aprobacion         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_acta               INT NOT NULL,
    id_usuario            INT NOT NULL,
    decision              VARCHAR(15) NOT NULL,
    comentario            VARCHAR(500) NULL,
    fecha_hora            TIMESTAMPTZ(0) NOT NULL CONSTRAINT df_aprobacion_acta_fecha DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_aprobacion_acta_acta FOREIGN KEY (id_acta) REFERENCES actas(id_acta),
    CONSTRAINT fk_aprobacion_acta_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT ck_aprobacion_acta_decision CHECK (decision IN ('APROBADA','RECHAZADA'))
);

CREATE TABLE tipos_epp (
    id_tipo_epp           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(80) NOT NULL UNIQUE,
    descripcion           VARCHAR(250) NULL,
    vida_util_dias        INT NULL,
    stock_minimo          INT NOT NULL CONSTRAINT df_tipo_epp_stock_min DEFAULT (0),
